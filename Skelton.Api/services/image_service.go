// ImageService handles image generation
type ImageService struct{}

// NewImageService creates a new image service instance
func NewImageService() *ImageService {
	return &ImageService{}
}

// GenerateFolderStructureImage generates a JPG image of the folder structure
func (s *ImageService) GenerateFolderStructureImage(content *models.AIGeneratedContent) ([]byte, error) {
	// Calculate image dimensions based on folder tree depth and size
	treeLines := s.countTreeLines(content.FolderStructure.Tree, 0)
	width := 1200
	height := max(800, treeLines*25+100)

	// Create a new image context
	dc := gg.NewContext(width, height)

	// Set white background
	dc.SetColor(color.White)
	dc.Clear()

	// Add title
	dc.SetColor(color.RGBA{31, 73, 125, 255})
	if err := dc.LoadFontFace("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 28); err != nil {
		// Fallback if font not found
		dc.SetColor(color.Black)
	}
	dc.DrawString("Project Folder Structure", 40, 50)

	// Add subtitle
	dc.SetColor(color.RGBA{100, 100, 100, 255})
	if err := dc.LoadFontFace("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 14); err == nil {
		dc.DrawString("Root: "+content.FolderStructure.RootFolder, 40, 80)
	}

	// Draw folder tree
	dc.SetColor(color.Black)
	if err := dc.LoadFontFace("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", 12); err == nil {
		s.drawFolderTree(dc, content.FolderStructure.Tree, 40, 120, 0)
	} else {
		// Fallback to default font
		s.drawFolderTree(dc, content.FolderStructure.Tree, 40, 120, 0)
	}

	// Add footer
	dc.SetColor(color.RGBA{150, 150, 150, 255})
	if err := dc.LoadFontFace("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 10); err == nil {
		dc.DrawString("Generated by Skelton API", 40, float64(height-20))
	}

	// Encode to JPEG
	var buf bytes.Buffer
	img := dc.Image()
	err := jpeg.Encode(&buf, img, &jpeg.Options{Quality: 95})
	if err != nil {
		return nil, fmt.Errorf("failed to encode image: %w", err)
	}

	return buf.Bytes(), nil
}

// drawFolderTree draws the folder tree on the image
func (s *ImageService) drawFolderTree(dc *gg.Context, nodes []models.FolderNode, x, y float64, level int) float64 {
	lineHeight := 22.0
	indent := 25.0
	currentY := y

	for i, node := range nodes {
		// Draw connector lines
		if level > 0 {
			dc.SetColor(color.RGBA{200, 200, 200, 255})
			dc.DrawLine(x-15, currentY-5, x-5, currentY-5)
			dc.Stroke()
		}

		// Draw icon and text
		icon := ""
		var nodeColor color.Color
		if node.Type == "folder" {
			icon = "📁"
			nodeColor = color.RGBA{0, 100, 200, 255}
		} else {
			icon = "📄"
			nodeColor = color.RGBA{80, 80, 80, 255}
		}

		dc.SetColor(nodeColor)
		text := fmt.Sprintf("%s %s", icon, node.Name)
		dc.DrawString(text, x+float64(level)*indent, currentY)

		currentY += lineHeight

		// Draw children recursively
		if len(node.Children) > 0 {
			// Draw vertical line for children
			if level >= 0 {
				dc.SetColor(color.RGBA{200, 200, 200, 255})
				childrenHeight := float64(s.countTreeLines(node.Children, 0)) * lineHeight
				dc.DrawLine(x+float64(level)*indent+10, currentY-lineHeight+5, x+float64(level)*indent+10, currentY+childrenHeight-lineHeight-5)
				dc.Stroke()
			}
			currentY = s.drawFolderTree(dc, node.Children, x, currentY, level+1)
		}

		// Add spacing between siblings at the same level
		if i < len(nodes)-1 {
			currentY += 3
		}
	}

	return currentY
}

// countTreeLines counts the total number of lines in the tree
func (s *ImageService) countTreeLines(nodes []models.FolderNode, level int) int {
	count := 0
	for _, node := range nodes {
		count++
		if len(node.Children) > 0 {
			count += s.countTreeLines(node.Children, level+1)
		}
	}
	return count
}

